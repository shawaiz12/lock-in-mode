// Regenerates src/api/schema.d.ts: TypeScript types for every API path and model,
// made from the API's OpenAPI schema (the same one behind /docs).
//
//   npm run api:types                              local API: http://localhost:8000/openapi.json
//   npm run api:types -- --from https://.../openapi.json
//   npm run api:types -- --from openapi.json --check   (CI) fail if schema.d.ts is out of date
//
// Run it after any backend change to routes or schemas, then commit schema.d.ts with
// that change. .NET: like regenerating an NSwag client from swagger.json.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const OUTPUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'api', 'schema.d.ts');
const HEADER =
  '// Generated by `npm run api:types` from the API\'s OpenAPI schema. Do not edit by hand.\n\n';

const args = process.argv.slice(2);
const check = args.includes('--check');
const fromIndex = args.indexOf('--from');
const from = fromIndex >= 0 ? args[fromIndex + 1] : 'http://localhost:8000/openapi.json';
if (!from) {
  console.error('--from needs a URL or a file path');
  process.exit(2);
}

async function readSchema(source) {
  if (/^https?:\/\//.test(source)) {
    const response = await fetch(source);
    if (!response.ok) throw new Error(`${source} answered ${response.status}`);
    return response.json();
  }
  return JSON.parse(fs.readFileSync(source, 'utf8'));
}

const schema = await readSchema(from);
// defaultNonNullable off: a field with a default is optional to SEND (PATCH /me can leave
// share_usage_data out). Fields the API always returns are listed as required anyway.
const generated = HEADER + astToString(await openapiTS(schema, { defaultNonNullable: false }));

if (check) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
  if (current !== generated) {
    console.error(
      'src/api/schema.d.ts is out of date with the API. Run `npm run api:types` ' +
        '(with the API running) and commit the result.',
    );
    process.exit(1);
  }
  console.log('src/api/schema.d.ts matches the API.');
} else {
  fs.writeFileSync(OUTPUT, generated);
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)} from ${from}`);
}
